// Turns design-reference/illustrations/*.svg into src/components/illustrations.generated.ts
// Run: npm run illustrations  (after adding or editing an SVG)
import fs from "node:fs";
import path from "node:path";
const dir = path.resolve("design-reference/illustrations");
const out = {};
for (const f of fs.readdirSync(dir).filter((f) => f.endsWith(".svg")).sort()) {
  let s = fs.readFileSync(path.join(dir, f), "utf8").trim();
  s = s.replace(/<svg([^>]*?)\s(width|height)="[^"]*"/g, "<svg$1").replace(/<svg([^>]*?)\s(width|height)="[^"]*"/g, "<svg$1");
  s = s.replace("<svg", '<svg width="100%" height="100%" preserveAspectRatio="xMidYMid meet"');
  s = s.replace(/\n\s*/g, " ");
  const key = f.replace(/\.svg$/, "").replace(/^q-/, "").replace(/-([a-z])/g, (_, c) => c.toUpperCase());
  out[key] = s;
}
const body = `// GENERATED by scripts/build-illustrations.mjs — edit the SVGs in design-reference/illustrations instead.\nexport const SVGS = ${JSON.stringify(out, null, 1)} as const;\n`;
fs.writeFileSync("src/components/illustrations.generated.ts", body);
console.log("Illustrations:", Object.keys(out).join(", "));
